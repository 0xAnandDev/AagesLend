#!/usr/bin/env node
// Copies ABIs from Foundry's out/ and addresses from deployments/ into the frontend as typed TS modules.
// Usage: forge build && node scripts/export-abis.mjs
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "out");
const target = join(root, "frontend", "src", "contracts");
const contracts = ["LendingPool", "ALToken", "ChainlinkOracle", "InterestRateModel", "MockERC20", "MockV3Aggregator"];

if (!existsSync(outDir)) {
  console.error("out/ not found. Run `forge build` first.");
  process.exit(1);
}
mkdirSync(target, { recursive: true });

const header = "// Generated by scripts/export-abis.mjs. Do not edit by hand.\n";
const lcFirst = (s) => s.charAt(0).toLowerCase() + s.slice(1);

let abis = header;
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(outDir, `${name}.sol`, `${name}.json`), "utf8"));
  abis += `\nexport const ${lcFirst(name)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}
writeFileSync(join(target, "abis.ts"), abis);

// The indexer and keeper only need the pool ABI.
const poolArtifact = JSON.parse(readFileSync(join(outDir, "LendingPool.sol", "LendingPool.json"), "utf8"));
for (const dir of ["indexer", "keeper"]) {
  const abiDir = join(root, dir, "abis");
  if (!existsSync(join(root, dir))) continue;
  mkdirSync(abiDir, { recursive: true });
  writeFileSync(
    join(abiDir, "LendingPoolAbi.ts"),
    `${header}\nexport const LendingPoolAbi = ${JSON.stringify(poolArtifact.abi, null, 2)} as const;\n`,
  );
}

const deploymentsDir = join(root, "deployments");
const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const file of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, file), "utf8"));
    deployments[d.chainId] = d;
  }
}
writeFileSync(
  join(target, "deployments.ts"),
  `${header}\nexport const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n\nexport type SupportedChainId = keyof typeof deployments;\n`,
);

console.log(`Wrote ${contracts.length} ABIs and ${Object.keys(deployments).length} deployment(s) to ${target}`);
